def read(p):
    with io.open(p, encoding="utf-8") as f:
        return f.read()


def has_real_3b(t):
    """判断是否已有实质 ③-B 内容（非模板占位）"""
    m = re.search(r"###\s*③-B[^\n]*\n(.*?)(?=\n##\s|\Z)", t, re.S)
    if not m:
        return False
    sec = m.group(1)
    lines = [l for l in sec.split("\n")
             if not l.strip().startswith("<!--")
             and not l.strip().startswith("★")
             and not l.strip().startswith("【")
             and "____" not in l
             and l.strip() not in ("-", "- ")]
    return len([l for l in lines if l.strip().startswith("-")]) > 0


def insert_3b(t, block):
    """在 ③ 区之后插入 ③-B 区（只增不删）"""
    if has_real_3b(t):
        return t, False
    lines = t.split("\n")
    # 定位 ③ 区标题行
    idx3 = None
    for i, l in enumerate(lines):
        if re.match(r"^##\s*③[^\n]*", l):
            idx3 = i
            break
    if idx3 is None:
        return t, False
    # 找到 ③ 区结束（下一个 ## 标题）
    end = len(lines)
    for j in range(idx3 + 1, len(lines)):
        if lines[j].startswith("## "):
            end = j
            break
    # 在 ③ 区结束后插入
    new_lines = lines[:end] + [""] + block.rstrip("\n").split("\n") + [""] + lines[end:]
    return "\n".join(new_lines), True


def audit():
    """巡检全库 ③-B 填卡率"""
    files = [f for f in sorted(os.listdir(CARD_DIR)) if f.endswith(".md") and f != "_模板_决策卡.md"]
    rows = []
    for fn in files:
        t = read(os.path.join(CARD_DIR, fn))
        has_sec = "③-B" in t or "信号触发后的立即动作" in t
        filled = has_real_3b(t)
        rows.append((fn, has_sec, filled))
    total = len(rows)
    filled_n = sum(1 for r in rows if r[2])
    has_n = sum(1 for r in rows if r[1])
    print(f"=== ③-B 区巡检（全库 {total} 张）===")
    print(f"含 ③-B 子栏      : {has_n}/{total} = {has_n/total*100:.1f}%")
    print(f"③-B 有实质填写    : {filled_n}/{total} = {filled_n/total*100:.1f}%")
    print(f"缺口（未填/无区） : {total-filled_n} 张")
    print()
    print("--- 缺口清单 ---")
    for fn, hs, fl in rows:
        if not fl:
            state = "有区未填" if hs else "无③-B区"
            print(f"  · {fn[:56]:58s} {state}")
    print()
    print("--- 已填明细 ---")
    for fn, hs, fl in rows:
        if fl:
            print(f"  ✅ {fn}")
    return rows


def apply(backup_dir):
    """执行回填"""
    os.makedirs(backup_dir, exist_ok=True)
    done, skipped = [], []
    for fn, block in BACKFILL.items():
        p = os.path.join(CARD_DIR, fn)
        t = read(p)
        if has_real_3b(t):
            skipped.append((fn, "已有实质 ③-B 内容"))
            continue
        # 备份
        bp = os.path.join(backup_dir, fn)
        with io.open(bp, "w", encoding="utf-8") as f:
            f.write(t)
        new, changed = insert_3b(t, block)
        if not changed:
            skipped.append((fn, "未找到 ③ 区锚点"))
            continue
        # 安全断言（逐行）：原文件的每一行都必须在新文件中原样出现且顺序不变
        # （不能用 `t.strip() in new` —— 插入会改变行尾，断言会误判）
        old_lines = [l for l in t.split("\n")]
        new_lines = [l for l in new.split("\n")]
        it = iter(new_lines)
        missing = None
        for ol in old_lines:
            for nl in it:
                if nl == ol:
                    break
            else:
                missing = ol
                break
        if missing is not None:
            skipped.append((fn, f"安全断言失败：原行未保留 → {missing[:50]}"))
            continue
        with io.open(p, "w", encoding="utf-8") as f:
            f.write(new)
        done.append(fn)
    return done, skipped


def verify():
    """回读验证"""
    ok = True
    for fn in BACKFILL:
        p = os.path.join(CARD_DIR, fn)
        t = read(p)
        if not has_real_3b(t):
            print(f"  ❌ {fn} ③-B 仍无实质内容")
            ok = False
        else:
            n = len(re.findall(r"^\- 信号", t, re.M))
            fb = len(re.findall(r"\*\*兜底路径\*\*", t))
            print(f"  ✅ {fn[:50]:52s} 信号动作 {n} 条 · 兜底路径 {fb} 条")
    return ok


def main():
    mode = sys.argv[1] if len(sys.argv) > 1 else "--audit"
    if mode == "--audit":
        audit()
        return 0
    if mode == "--apply":
        BK = sys.argv[2] if len(sys.argv) > 2 else "/tmp/3b-backfill-backup"
        done, skipped = apply(BK)
        print(f"=== 回填完成：成功 {len(done)} 张，跳过 {len(skipped)} 张 ===")
        for f in done:
            print(f"  ✅ {f}")
        for f, r in skipped:
            print(f"  ⏭️  {f} — {r}")
        print(f"\n备份目录: {BK}")
        return 0
    if mode == "--verify":
        print("=== 回读验证 ===")
        return 0 if verify() else 1
    print("用法: python3 backfill_3b.py [--audit|--apply <备份目录>|--verify]")
    return 2


if __name__ == "__main__":
    sys.exit(main())
