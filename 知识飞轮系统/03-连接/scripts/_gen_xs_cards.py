def load(fn):
    return open(fn, encoding="utf-8").read()

TXT = {k: load(v) for k, v in FILES.items()}

def grab(filekey, anchor, maxlen=900):
    """抽取 anchor 之后到下一个 '▶' 或 '【章】' 标记前的正文，作为裁判规则依据。"""
    t = TXT[filekey]
    i = t.find(anchor)
    if i < 0:
        # 尝试去掉首尾空白再找
        for line in t.split("\n"):
            if anchor.strip() in line:
                i = t.find(line); break
    if i < 0:
        return "（原文锚点未精确定位，详见来源文件对应章节）"
    seg = t[i+len(anchor):]
    # 截断到下一个争点标记
    cut = re.search(r"\n[▶【]", seg)
    if cut:
        seg = seg[:cut.start()]
    seg = re.sub(r"={5,}PDF页.*?={5,}", " ", seg)
    seg = re.sub(r"\n{2,}", "\n", seg).strip()
    # 去掉行首多余空格
    lines = [l.strip() for l in seg.split("\n") if l.strip()]
    out = "\n".join(lines)
    return out[:maxlen] if len(out) > maxlen else out

