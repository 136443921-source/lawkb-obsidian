def cn2num(s):
    if s.isdigit():
        return int(s)
    digits = {'零':0,'一':1,'二':2,'两':2,'三':3,'四':4,'五':5,'六':6,'七':7,'八':8,'九':9}
    units = {'十':10,'百':100,'千':1000}
    total = 0; cur = 0
    for ch in s:
        if ch in digits:
            cur = digits[ch]
        elif ch in units:
            cur = 1 if cur == 0 else cur
            total += cur * units[ch]; cur = 0
        else:
            return None
    return total + cur

def fill_statute(body):
    out = []
    # 卡行格式：「- 《刑法》第三百八十五条（受贿罪）」或「- 《刑法》第三百八十八条之一（利用影响力受贿）」
    # 行尾是「（罪名）」而非「条」，且「之一」须捕获进独立组，否则 key 会错算成 388 而非 "388之一"
    line_pat = re.compile(r"- 《刑法》第([一二三四五六七八九十百零两\d]+)(之一)?[（条]")
    for line in body.split("\n"):
        out.append(line)
        m = line_pat.match(line)
        if m:
            no = m.group(1)
            suffix = m.group(2) or ""
            key = (str(cn2num(no)) + suffix) if suffix else cn2num(no)
            if key in DATA:
                verb, suf = DATA[key]
                out.append("")
                for vl in verb.split("\n"):
                    out.append(f"> {vl}")
                out.append(f"> 〔来源：企查查法律数据(qcc-legal)·《中华人民共和国刑法(2023修正)》·现行有效｜[链接]({URL.format(s=suf)})〕")
            else:
                out.append(f"> ⚠️ 未匹配 verbatim 条号: {key}")
    return "\n".join(out)

