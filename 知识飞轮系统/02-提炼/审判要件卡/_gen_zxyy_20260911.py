    fm = re.sub(r'\*\*\*\*', '**', fm)
    # 坑20兜底：双书名号
    fm = re.sub(r'《《(.+?)》([^》]*)》', r'《\1》\2', fm)

    fn = f"{OUTDIR}/{rid}-{c['slug']}.md"
    open(fn, 'w', encoding='utf-8').write(fm)
    return fn


