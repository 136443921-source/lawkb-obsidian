def yq(s):
    out, q = [], True
    for ch in str(s):
        if ch == '"':
            out.append("\u300c" if q else "\u300d"); q = not q
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def book(n):
    n = str(n).strip()
    return n if "《" in n else f"《{n}》"


def pg(a, b):
    return f"（PDF页{a+1}-{b+1}·书页{MP[str(a)]}-{MP[str(b)]}）"


def laws(items):
    """items: list of (法名, 条号, 摘要, cite_key)"""
    rows = ["| 法条 | 要旨 | 出处 |", "|---|---|---|"]
    for name, art, gist, key in items:
        rows.append(f"| {book(name)} {art} | {gist} | [{QCC}]({CIT[key]}) |")
    return "\n".join(rows)


