def scan_pollution():
    hits = []
    for c in CARDS:
        blob = c['title'] + c['burden'] + c['negative'] + c['review_step']
        for k, v in c['body'].items():
            blob += v
        blob = URL_RE.sub('', blob)   # 先剥离核验链接，避免 URL 内 legal/regulation/hex 误报
        for m in LATIN.findall(blob):
            if m.upper() not in WHITE:
                hits.append((c['rid'], m))
        for k in KANA.findall(blob):
            hits.append((c['rid'], 'kana:' + k))
    return hits

