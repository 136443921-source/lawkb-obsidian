# ---------- 坑1：YAML 双引号转义 ----------
def yq(s):
    out = []
    open_q = True
    for ch in str(s):
        if ch == '"':
            out.append('\u300c' if open_q else '\u300d')
            open_q = not open_q
        else:
            out.append(ch)
    return '"' + ''.join(out) + '"'

def law(lawkey, art, note=''):
    """从法条库取正文，绝不凭记忆"""
    blk = LAW.get(lawkey)
    assert blk, f'法条库缺 {lawkey}'
    body = blk.get(art)
    assert body, f'法条库缺 {lawkey} {art}'
    full = blk.get('_full', lawkey)
    fwzh = blk.get('_fwzh', '')
    name = f'《{full}》' + (f'（{fwzh}）' if fwzh else '')
    s = f'**{name}{art}**\n\n> {body}\n\n*效力状态：{blk.get("_sxx","现行有效")}（{blk.get("_src","")}）*'
    if note:
        s += f'\n\n{note}'
    return s

