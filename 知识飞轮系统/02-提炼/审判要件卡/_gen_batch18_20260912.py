def yq(s):
    out, q = [], True
    for ch in str(s):
        if ch == '"':
            out.append("\u300c" if q else "\u300d"); q = not q
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def book(n):
    n = str(n).strip()
    return n if "《" in n else f"《{n}》"


