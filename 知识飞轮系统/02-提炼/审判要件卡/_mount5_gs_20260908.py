print("✓ 变更记录加 1.29.0")

# 5) version + updated（两处同步）
src = src.replace("version: 1.28.0", "version: 1.29.0", 1)
src = re.sub(r"^updated: .*$", "updated: 2026-09-08T12:20", src, count=1, flags=re.M)
