lines = src.split("\n")
# 插到变更记录表首行数据前（找最后一行 "| 1.xx.0 |" 之后的表头之后）
ti = None
for n, l in enumerate(lines):
    if l.startswith("| 1.28.0 |"):
        ti = n; break
