def yq(s):
    """YAML 安全引号（坑 1 / 坑 27）：中文引号统一转义为「」"""
    out, open_q = [], True
    for ch in str(s):
        if ch == '"':
            out.append("\u300c" if open_q else "\u300d")
            open_q = not open_q
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def wrap_book(name):
    n = str(name).strip()
    return n if "《" in n else f"《{n}》"


def render_statutes(refs):
    """refs: [(law, article)] 或 (law, article, override_text)"""
    lines = []
    for law, art in refs:
        text, tag, link = CIT[(law, art)]
        lines.append(f"**{wrap_book(law)}{art}**（{tag}）")
        lines.append(f"> {text}")
        lines.append(">")
        lines.append(f"> 核验链接：{link}")
        lines.append("")
    return "\n".join(lines)


