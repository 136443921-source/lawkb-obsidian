CN = {'0': '零', '1': '一', '2': '二', '3': '三', '4': '四',
      '5': '五', '6': '六', '7': '七', '8': '八', '9': '九'}


def cn_num(n):
    """阿拉伯数字 → 中文条号用数字（处理 1090→一千零九十、1220→一千二百二十）"""
    s = str(int(n))
    if len(s) == 1:
        return CN[s]
    if len(s) == 2:
        t, o = s[0], s[1]
        r = ('十' if t == '1' else CN[t] + '十')
        return r + (CN[o] if o != '0' else '')
    if len(s) == 3:
        h, t, o = s
        r = CN[h] + '百'
        if t == '0' and o != '0':
            r += '零'
        elif t != '0':
            r += ('一十' if t == '1' else CN[t] + '十')
        return r + (CN[o] if o != '0' else '')
    # 四位数
    th, h, t, o = s
    r = CN[th] + '千'
    if h == '0' and (t != '0' or o != '0'):
        r += '零'
    elif h != '0':
        r += CN[h] + '百'
    if h != '0' and t == '0' and o != '0':
        r += '零'
    if t != '0':
        r += ('一十' if t == '1' else CN[t] + '十')
    if o != '0':
        r += CN[o]
    return r


def extract_local(path, nums, law_name, source_tag):
    """本地全文 md 提取：行首锚定 + 取首次出现（防交叉引用覆盖）"""
    txt = open(path, encoding='utf-8').read()
    out, miss = {}, []
    for n in nums:
        art = cn_num(n)
        pat = re.compile(r'(?m)^\s*第%s条[ 　]*([^\n]*)(?:\n(?![\t 　]*第[零一二三四五六七八九十百千]+条)[^\n]*)*' % art)
        m = pat.search(txt)
        if not m:
            miss.append(art)
            continue
        body = re.sub(r'[ 　]+', ' ', m.group(0)).strip()
        out["%s|第%s条" % (law_name, art)] = {
            "law": law_name, "article": "第%s条" % art, "text": body,
            "source": source_tag, "timeliness": "现行有效",
        }
    if miss:
        print("  !! %s MISS: %s" % (law_name, miss))
    return out


def extract_inline(raw, law_name, source_tag, max_art=999):
    """把权威源贴回的全文按「第X条」切片"""
    out = {}
    parts = re.split(r'(?m)^\s*第([零一二三四五六七八九十百千]+)条', raw)
    # parts: [前导, 条号1, 正文1, 条号2, 正文2, ...]
    for i in range(1, len(parts), 2):
        art = "第%s条" % parts[i]
        body = re.sub(r'[ 　]+', ' ', parts[i + 1]).strip()
        body = re.sub(r'\n+', ' ', body)
        out["%s|%s" % (law_name, art)] = {
            "law": law_name, "article": art, "text": body.strip(),
            "source": source_tag, "timeliness": "现行有效",
        }
    return out


