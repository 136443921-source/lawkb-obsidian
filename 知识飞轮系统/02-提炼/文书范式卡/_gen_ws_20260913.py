def yq(s):
    """frontmatter 双引号值转义：英文双引号 -> 中文引号，防 YAML 解析失败（拆卡流水线坑1）"""
    out = []
    open_q = True
    for ch in str(s):
        if ch == '"':
            out.append('「' if open_q else '」')
            open_q = not open_q
        else:
            out.append(ch)
    return '"' + ''.join(out) + '"'

def fm(d):
    lines = ["---"]
    for k, v in d.items():
        if isinstance(v, list):
            if not v:
                lines.append(f"{k}: []")
            else:
                lines.append(f"{k}:")
                for item in v:
                    if isinstance(item, dict):
                        lines.append(f"  - {yq(item['name'])}")
                    else:
                        lines.append(f"  - {yq(item)}")
        elif isinstance(v, bool):
            lines.append(f"{k}: {'true' if v else 'false'}")
        else:
            lines.append(f"{k}: {yq(v)}")
    lines.append("---")
    return "\n".join(lines)

