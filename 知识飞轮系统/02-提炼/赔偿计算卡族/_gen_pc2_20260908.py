def write_cards(cards, dstdir):
    written = []
    for c in cards:
        path = os.path.join(dstdir, c["fname"] + ".md")
        with open(path, "w", encoding="utf-8") as f:
            f.write(render(c, dstdir))
        written.append((c["rid"], path))
    return written

