TITLE_RE=re.compile(r'^\s*\S+\s*[．.,，、]\s*\S+纠纷\s*$')
def find_block(name):
    # 标题行: 行首(允许缩进) 非空串+分隔符+name 结尾；向后400行找首个【释义/【管辖/案由应当注意 标记确认是详细正文(非TOC)
    are=re.compile(r'^\s*\S+\s*[．.,，、]\s*'+re.escape(name)+r'(?:\s*$|【)')
    cands=[]
    for i,ln in enumerate(lines):
        if are.search(ln) and "【" not in ln.split(name)[0][-4:]:
            cands.append(i)
    for i in cands:
        end=len(lines)
        for k in range(i+1,min(i+400,len(lines))):
            if TITLE_RE.match(lines[k]) and k!=i:
                end=k; break
        blk="\n".join(lines[i:end])
        if "【释义" in blk or "【管辖" in blk or "案由应当注意" in blk or "确定该案由" in blk:
            return i
    return (cands[0] if cands else None)

def next_header(start):
    for k in range(start+1,len(lines)):
        if TITLE_RE.match(lines[k]): return k
    return len(lines)

def split_sections(block_lines):
    secs={"释义":"","管辖":"","法律适用":"","注意":""}
    cur=None
    for ln in block_lines:
        if "【释义" in ln: cur="释义"; continue
        if "【管辖" in ln: cur="管辖"; continue
        if "【法律适用" in ln: cur="法律适用"; continue
        if "案由应当注意" in ln or "确定该案由" in ln: cur="注意"; continue
        if "<<<PAGE" in ln: continue
        if cur: secs[cur]+=ln+"\n"
    return secs

