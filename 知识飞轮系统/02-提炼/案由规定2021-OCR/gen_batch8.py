def find_block(anchor_re):
    # 优先：锚点行 + 下一非空行含【释义】
    for i,ln in enumerate(lines):
        if re.search(anchor_re,ln):
            j=i+1
            while j<len(lines) and lines[j].strip()=="" : j+=1
            if j<len(lines) and "【释义】" in lines[j]:
                return i
    for i,ln in enumerate(lines):
        if re.search(anchor_re,ln): return i
    return None

def next_header(start):
    pat=re.compile(r'^\s*\d{3}\s*[．.,，、]\s*.{0,30}?纠纷')
    for k in range(start+1,len(lines)):
        if pat.match(lines[k]) and "【释义】" not in lines[k]:
            return k
    return len(lines)

def split_sections(block_lines):
    secs={"释义":"","管辖":"","法律适用":"","注意":""}
    cur=None
    for ln in block_lines:
        if "【释义】" in ln: cur="释义"; continue
        if "【管辖】" in ln: cur="管辖"; continue
        if "【法律适用】" in ln: cur="法律适用"; continue
        if "【确定该案由应当注意的问题】" in ln: cur="注意"; continue
        if cur: secs[cur]+=ln+"\n"
    return secs

